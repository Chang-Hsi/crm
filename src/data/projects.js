const accountById = new Map(accountList.map((item) => [item.id, item]));
const opportunityById = new Map(opportunityList.map((item) => [item.id, item]));
const contractById = new Map(contractList.map((item) => [item.id, item]));
const userById = new Map(userList.map((item) => [item.id, item]));

function resolveAccountName(accountId, fallback = "") {
  return accountById.get(accountId)?.companyName ?? fallback;
}

function resolveOpportunityName(opportunityId, fallback = "") {
  return opportunityById.get(opportunityId)?.name ?? fallback;
}

function resolveContractName(contractId, fallback = "") {
  return contractById.get(contractId)?.contractName ?? fallback;
}

function resolveOwnerName(ownerId, fallback = "未指派") {
  return userById.get(ownerId)?.name ?? fallback;
}

function resolveMemberNames(memberIds = []) {
  return memberIds.map((userId) => resolveOwnerName(userId, userId));
}

function milestone(id, name, status, dueDate, completedAt) {
  return { id, name, status, dueDate, completedAt };
}

function activity(id, occurredAt, title, description, actorName) {
  return { id, occurredAt, title, description, actorName };
}

function createProjectRecord(record) {
  return {
    ...record,
    customerName: resolveAccountName(record.customerId, record.customerName),
    opportunityName: resolveOpportunityName(record.opportunityId, record.opportunityName),
    contractName: resolveContractName(record.contractId, record.contractName),
    ownerName: resolveOwnerName(record.ownerId, record.ownerName),
    memberNames: resolveMemberNames(record.members ?? []),
  };
}

